/// 심화 기술 연습에서 가르치는 기술 하나의 설명.
class TechniqueInfo {
  const TechniqueInfo({
    required this.technique,
    required this.summary,
    required this.what,
    required this.how,
    this.fill = false,
    this.placeOne = false,
  });

  final Technique technique;

  /// 목록에 보이는 한 줄 설명.
  final String summary;

  /// 기술이 무엇인지.
  final String what;

  /// 판에서 어떻게 찾는지.
  final String how;

  /// true이면 후보를 지우는 대신 숫자를 3개 채우는 연습 (싱글 기술).
