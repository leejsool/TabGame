  /// true이면 후보를 지우는 대신 정답 한 칸을 찾아 넣는 연습 (BUG+1).
  final bool placeOne;

  String get id => 'sudoku_${technique.name}';
  String get label => technique.label;
  int get level => technique.level;
}

