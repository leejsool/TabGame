/// 연습용 예제 한 판: 지금까지 채워진 숫자와, 이미 지워진 후보.
///
/// 이 상태에서 [Technique]이(가) "다음으로 쉬운 논리 단계"가 되도록 골랐다.
/// (technique_examples_test.dart가 이 사실을 검증한다.)
class TechniqueExample {
  const TechniqueExample(this.values, [this.elims = '']);

  /// 칸 0~80의 숫자 (0 = 빈 칸).
  final String values;

  /// 이미 지운 후보: "칸:마스크,칸:마스크" (마스크는 숫자 1→bit0 … 9→bit8).
  final String elims;

  List<int> get valueList => [for (final ch in values.split('')) int.parse(ch)];

  List<int> get elimList {
    final out = List<int>.filled(81, 0);
    if (elims.isEmpty) return out;
    for (final part in elims.split(',')) {
      final kv = part.split(':');
      out[int.parse(kv[0])] = int.parse(kv[1]);
    }
    return out;
  }
}

